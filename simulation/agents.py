"""
Multi-Agent Weather Simulation — inspired by MiroFish (666ghj/MiroFish)

Simulation runs in two modes, selected automatically per-cycle:

  SCENARIO MODE (default, SCENARIO_SPECULATION=true):
    Phase 1 — Morgan (Scenario Architect) generates 2-3 explicit future weather
              scenarios with probability weights.
    Phase 2 — 4 analysts each estimate P(YES | scenario_i) independently.
    Phase 3 — River (Bayesian Synthesizer) computes the final weighted probability:
              P(YES) = Σ P(scenario_i) × mean_analyst_P(YES|scenario_i)
    Result: sharper probability estimates, especially when models disagree.
    Cost:   ~6 API calls vs 12 for classic debate (faster + cheaper).

  CLASSIC DEBATE MODE (fallback / SCENARIO_SPECULATION=false):
    4 analysts debate for SIM_ROUNDS rounds; consensus = average final estimates.
    Used when scenario mode is disabled or Morgan fails to produce valid scenarios.

Learning integration (both modes):
  - Lessons from ExperienceMemory injected into every analyst system prompt.
  - Persona biases augmented with learned calibration updates at runtime.
"""
from __future__ import annotations

import json
import logging
import re
from dataclasses import dataclass, field
from typing import TYPE_CHECKING, Optional

from config import (
    MAX_AGENTS_PER_SIM, SIM_ROUNDS,
    PERSONA_WEIGHTING, SCENARIO_SPECULATION, SCENARIO_THRESHOLD_F,
)
from llm_client import LLMClient
from weather_data import CityForecast

if TYPE_CHECKING:
    from learning.memory import ExperienceMemory

logger = logging.getLogger(__name__)

